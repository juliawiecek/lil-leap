package com.neueda.leap.onboarding.enums;

/**
 * Employment statuses collected for investor onboarding.
 */
public enum EmploymentStatus {
    /** Employed by an organization. */
    EMPLOYED,
    /** Works for their own business. */
    SELF_EMPLOYED,
    /** Retired from employment. */
    RETIRED,
    /** Currently a student. */
    STUDENT,
    /** Currently without employment. */
    UNEMPLOYED
}


