/**
 * Citizenship or residency statuses supported by onboarding.
 */
public enum CitizenshipStatus {
    /** Citizen of the declared country. */
    CITIZEN,
    /** Permanent resident of the declared country. */
    PERMANENT_RESIDENT,
    /** Another declared citizenship or residency status. */
    OTHER
}


