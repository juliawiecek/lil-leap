import { test, expect } from '@playwright/test';
import { advancedDesk } from './advanced-dashboard-fixture.mjs';

test('stock styles and adjustable averages use OHLC data and retain trading controls', async ({ page }, info) => {
  test.skip(info.project.metadata.role !== 'TRADER');
  const { ticket, state } = await advancedDesk(page, info);
  const chart = page.locator('app-advanced-chart');
  await expect(chart.locator('.price-line')).toBeVisible();
  await chart.getByRole('button', { name: 'Candles', exact: true }).click();
  await expect(chart.locator('.ohlc-glyph')).toHaveCount(30);
  await expect(chart.locator('.ohlc-glyph.down')).toHaveCount(15);
  await expect(chart.locator('.ohlc-glyph rect')).toHaveCount(30);
  await expect(chart.locator('.price-line')).toHaveCount(0);
  await chart.locator('svg').focus(); await chart.locator('svg').press('Home');
  await expect(chart.locator('.stock-tooltip')).toContainText('O $89.50');
  await expect(chart.locator('.stock-tooltip')).toContainText('H $92.00');
  await expect(chart.locator('.stock-tooltip')).toContainText('L $88.00');
  await chart.getByLabel('SMA', { exact: true }).check();
  await expect(chart.locator('.sma-line')).toHaveAttribute('d', /^M.*L/);
  const oldPath = await chart.locator('.sma-line').getAttribute('d');
  await chart.getByLabel('SMA periods', { exact: true }).fill('5');
  await expect(chart.locator('.sma-line')).not.toHaveAttribute('d', oldPath);
  await chart.getByLabel('EMA', { exact: true }).check();
  await expect(chart).toContainText('EMA needs');
  await chart.getByLabel('EMA periods', { exact: true }).fill('10');
  await expect(chart.locator('.ema-line')).toHaveAttribute('d', /^M.*L/);
  await chart.getByRole('button', { name: 'OHLC bars', exact: true }).click();
  await expect(chart.locator('.ohlc-glyph rect')).toHaveCount(0);
  await expect(chart.locator('.ohlc-glyph line')).toHaveCount(90);
  await chart.getByLabel('Bar interval', { exact: true }).selectOption('15m');
  await expect(chart.locator('.ohlc-glyph')).toHaveCount(30);
  await chart.getByRole('button', { name: 'Line', exact: true }).click();
  await expect(chart.locator('.price-line')).toBeVisible();
  await expect(chart.locator('.sma-line')).toBeVisible();
  await expect(ticket.getByRole('button', { name: 'Review Order', exact: true })).toBeVisible();
  const failCandles = route => route.fulfill({ status: 503, json: {} });
  await page.route('**/quotes/candles/**', failCandles);
  await expect(chart.getByRole('alert')).toContainText('could not be refreshed', { timeout: 12000 });
  await page.unroute('**/quotes/candles/**', failCandles);
  await chart.getByRole('button', { name: 'Retry candles' }).click();
  await expect(chart.getByRole('alert')).toHaveCount(0);
  await page.setViewportSize({ width: 390, height: 844 });
  await chart.getByRole('button', { name: 'Candles', exact: true }).click();
  await chart.locator('section').screenshot({ path: info.outputPath('candles-mobile.png') });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(state.errors).toEqual([]);
});
